// Generates tokens.css (Tailwind v4 @theme + light/dark CSS variables) from src/tokens.ts.
// Run with Node ≥ 23.6 (native TypeScript type stripping): `node scripts/build-css.ts`.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dark, font, light, radius, type ColorScheme } from '../src/tokens.ts';

const vars = (s: ColorScheme): string =>
  [
    ['bg', s.bg],
    ['surface', s.surface],
    ['surface-muted', s.surfaceMuted],
    ['border', s.border],
    ['border-strong', s.borderStrong],
    ['text', s.text],
    ['text-muted', s.textMuted],
    ['text-inverse', s.textInverse],
    ['primary', s.primary],
    ['primary-hover', s.primaryHover],
    ['primary-text', s.primaryText],
    ['focus', s.focus],
    ...Object.entries(s.tones).flatMap(([tone, v]) => [
      [`${tone}-fg`, v.fg],
      [`${tone}-bg`, v.bg],
      [`${tone}-border`, v.border],
    ]),
  ]
    .map(([k, v]) => `  --hb-${k}: ${v};`)
    .join('\n');

const themeColors = [
  'bg',
  'surface',
  'surface-muted',
  'border',
  'border-strong',
  'text',
  'text-muted',
  'text-inverse',
  'primary',
  'primary-hover',
  'primary-text',
  'focus',
  ...['neutral', 'info', 'success', 'warning', 'danger', 'brand'].flatMap((t) => [
    `${t}-fg`,
    `${t}-bg`,
    `${t}-border`,
  ]),
]
  .map((k) => `  --color-${k}: var(--hb-${k});`)
  .join('\n');

const css = `/* AUTO-GENERATED by packages/design-tokens/scripts/build-css.ts — do not edit. */
@theme {
${themeColors}
  --font-sans: ${font.family.sans};
  --font-mono: ${font.family.mono};
  --radius-sm: ${radius.sm}px;
  --radius-md: ${radius.md}px;
  --radius-lg: ${radius.lg}px;
  --radius-xl: ${radius.xl}px;
}

:root {
  color-scheme: light;
${vars(light)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${vars(dark).replace(/^/gm, '  ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${vars(dark)}
}
`;

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'tokens.css'), css);
console.log('design-tokens: tokens.css written');

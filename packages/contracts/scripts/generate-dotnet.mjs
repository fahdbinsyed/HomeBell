// Emits C# constants for the .NET backend from the bundled contract (ADR-0004, ADR-0019):
//   backend/src/BuildingBlocks/HomeBell.BuildingBlocks.Domain/Contract/ErrorCodes.g.cs
//   backend/src/BuildingBlocks/HomeBell.BuildingBlocks.Domain/Contract/ContractEnums.g.cs
// String enums become `static class X { const string ... ; All }` so the backend uses exactly the
// contract's wire values (e.g. "active_paid", "school.admin") with no naming-policy guesswork.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(
  root,
  '../../backend/src/BuildingBlocks/HomeBell.BuildingBlocks.Domain/Contract',
);
const spec = yaml.load(readFileSync(join(root, 'bundled/openapi.v1.yaml'), 'utf8'));
const catalog = yaml.load(readFileSync(join(root, 'openapi/error-catalog.yaml'), 'utf8'));
const schemas = spec.components?.schemas ?? {};
const HEADER = `// <auto-generated>
// Generated by packages/contracts/scripts/generate-dotnet.mjs from contract ${spec.info.version}.
// Do not edit; run \`pnpm --filter @homebell/contracts generate\`.
// </auto-generated>
#nullable enable
`;

const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('')
    .replace(/^(\d)/, '_$1');
const str = (s) => JSON.stringify(s);

// ── Error codes ─────────────────────────────────────────────────────────
const codes = schemas.ErrorCode.enum;
const titleOf = (code) => catalog[code].description.replace(/`/g, '');
const errorFile = `${HEADER}
namespace HomeBell.BuildingBlocks.Domain.Contract;

/// <summary>Contract ErrorCode values with their HTTP status (packages/contracts/openapi/error-catalog.yaml).</summary>
public static class ErrorCodes
{
${codes.map((c) => `    public const string ${pascal(c.toLowerCase())} = ${str(c)};`).join('\n')}

    private static readonly Dictionary<string, (int Status, string Title)> Catalog = new(StringComparer.Ordinal)
    {
${codes.map((c) => `        [${str(c)}] = (${catalog[c].status}, ${str(titleOf(c))}),`).join('\n')}
    };

    public static IReadOnlyCollection<string> All => Catalog.Keys;

    public static int StatusOf(string code) => Catalog.TryGetValue(code, out var e) ? e.Status : 500;

    public static string TitleOf(string code) => Catalog.TryGetValue(code, out var e) ? e.Title : "Unexpected error.";

    public static bool IsKnown(string code) => Catalog.ContainsKey(code);
}
`;

// ── String enums ────────────────────────────────────────────────────────
const enums = Object.entries(schemas)
  .filter(([name, s]) => s?.type === 'string' && Array.isArray(s.enum) && name !== 'ErrorCode')
  .sort(([a], [b]) => a.localeCompare(b));
const enumFile = `${HEADER}
namespace HomeBell.BuildingBlocks.Domain.Contract;
${enums
  .map(([name, s]) => {
    const members = s.enum
      .map((v) => `    public const string ${pascal(v)} = ${str(v)};`)
      .join('\n');
    return `
/// <summary>Contract enum <c>${name}</c>.</summary>
public static class ${name}
{
${members}

    public static IReadOnlyList<string> All { get; } = [${s.enum.map(str).join(', ')}];

    public static bool IsValid(string? value) => value is not null && All.Contains(value, StringComparer.Ordinal);
}`;
  })
  .join('\n')}
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'ErrorCodes.g.cs'), errorFile.replace(/\r?\n/g, '\r\n'), 'utf8');
writeFileSync(join(outDir, 'ContractEnums.g.cs'), enumFile.replace(/\r?\n/g, '\r\n'), 'utf8');
console.log(`dotnet: ${codes.length} error codes, ${enums.length} enums`);

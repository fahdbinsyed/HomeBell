// Post-bundle generation for @homebell/contracts.
// - Verifies ErrorCode enum <-> error-catalog.yaml parity (fails the build on drift).
// - Emits src/generated/error-catalog.ts, src/generated/schemas.ts, src/generated/realtime.ts
// - Emits ERROR_CODES.md
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => yaml.load(readFileSync(join(root, p), 'utf8'));
const write = (p, content) => {
  mkdirSync(dirname(join(root, p)), { recursive: true });
  writeFileSync(join(root, p), content, 'utf8');
};
const HEADER = '// AUTO-GENERATED by packages/contracts/scripts/generate.mjs — do not edit.\n';

const spec = read('bundled/openapi.v1.yaml');
const catalog = read('openapi/error-catalog.yaml');
const schemas = spec.components?.schemas ?? {};

// ── Error catalog parity ────────────────────────────────────────────────
const enumCodes = schemas.ErrorCode?.enum;
if (!Array.isArray(enumCodes)) throw new Error('ErrorCode enum not found in bundled spec');
const catalogCodes = Object.keys(catalog);
const missing = enumCodes.filter((c) => !catalogCodes.includes(c));
const extra = catalogCodes.filter((c) => !enumCodes.includes(c));
if (missing.length || extra.length) {
  console.error('Error catalog drift detected.');
  if (missing.length)
    console.error('  In ErrorCode enum but not in error-catalog.yaml:', missing.join(', '));
  if (extra.length)
    console.error('  In error-catalog.yaml but not in ErrorCode enum:', extra.join(', '));
  process.exit(1);
}
for (const [code, info] of Object.entries(catalog)) {
  if (!Number.isInteger(info?.status) || info.status < 200 || info.status > 599)
    throw new Error(`error-catalog: ${code} has invalid status`);
  if (typeof info.description !== 'string' || !info.description)
    throw new Error(`error-catalog: ${code} has no description`);
}

const catalogEntries = enumCodes
  .map((code) => {
    const { status, description, meta = [] } = catalog[code];
    return `  ${code}: { status: ${status}, description: ${JSON.stringify(description)}, meta: ${JSON.stringify(meta)} },`;
  })
  .join('\n');
write(
  'src/generated/error-catalog.ts',
  `${HEADER}import type { ErrorCode } from './schemas';

export interface ErrorCodeInfo {
  readonly status: number;
  readonly description: string;
  /** Keys clients may rely on in Problem.meta for this code. */
  readonly meta: readonly string[];
}

export const ERROR_CATALOG = {
${catalogEntries}
} as const satisfies Record<ErrorCode, ErrorCodeInfo>;
`,
);

const mdRows = enumCodes
  .map((code) => {
    const { status, description, meta = [] } = catalog[code];
    return `| \`${code}\` | ${status} | ${description.replace(/\|/g, '\\|')} | ${meta.map((m) => `\`${m}\``).join(', ')} |`;
  })
  .join('\n');
write(
  'ERROR_CODES.md',
  `<!-- AUTO-GENERATED by packages/contracts/scripts/generate.mjs — edit openapi/error-catalog.yaml instead. -->
# HomeBell API error codes (v1)

Every error response is \`application/problem+json\` with a machine-readable \`code\`.
Clients must branch on \`code\` (never on \`detail\`) and tolerate unknown codes.

| Code | HTTP | Meaning | \`meta\` keys |
|---|---|---|---|
${mdRows}
`,
);

// ── Schema aliases ──────────────────────────────────────────────────────
const schemaNames = Object.keys(schemas).sort();
write(
  'src/generated/schemas.ts',
  `${HEADER}import type { components } from './openapi';

type S = components['schemas'];

${schemaNames.map((n) => `export type ${n} = S['${n}'];`).join('\n')}
`,
);

// ── Realtime constants from AsyncAPI ────────────────────────────────────
const asyncapi = read('realtime/realtime.asyncapi.yaml');
const hubs = {};
const serverEvents = new Set();
const hubMethods = {};
for (const [channelKey, channel] of Object.entries(asyncapi.channels)) {
  const hub = channelKey.replace(/Hub$/, '');
  hubs[hub] = channel.address;
}
for (const op of Object.values(asyncapi.operations)) {
  const channelKey = op.channel.$ref.split('/').pop();
  const hub = channelKey.replace(/Hub$/, '');
  for (const m of op.messages) {
    const msgKey = m.$ref.split('/').pop();
    const message = asyncapi.components.messages[msgKey];
    if (!message?.name) throw new Error(`AsyncAPI message ${msgKey} has no name`);
    if (op.action === 'send') serverEvents.add(message.name);
    else (hubMethods[hub] ??= []).push(message.name);
  }
}
const events = [...serverEvents].sort();
write(
  'src/generated/realtime.ts',
  `${HEADER}
/** SignalR hub paths. */
export const REALTIME_HUBS = ${JSON.stringify(hubs, null, 2)} as const;
export type RealtimeHub = keyof typeof REALTIME_HUBS;

/** The single client method through which every server event is delivered. */
export const REALTIME_CLIENT_METHOD = 'event' as const;

/** All server → client event types. */
export const REALTIME_EVENT_TYPES = ${JSON.stringify(events, null, 2)} as const;
export type RealtimeEventType = (typeof REALTIME_EVENT_TYPES)[number];

/** Client → server hub methods per hub. */
export const REALTIME_HUB_METHODS = ${JSON.stringify(hubMethods, null, 2)} as const;
`,
);

console.log(
  `contracts: ${enumCodes.length} error codes, ${schemaNames.length} schemas, ${events.length} realtime events generated.`,
);
